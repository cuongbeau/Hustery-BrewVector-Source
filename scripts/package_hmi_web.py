"""Deterministic gzip root, generated on every HMI build or directly."""
from pathlib import Path
import gzip, hashlib, re, runpy
if '__file__' in globals():
    root = Path(__file__).resolve().parents[1]
else:
    Import('env')
    root = Path(env['PROJECT_DIR']).resolve().parent
runpy.run_path(str(root / 'scripts/package_profiles.py'))
web = root / 'hmi/src/web'
for source, header, symbol in [
    ('connections.js', 'web_js_connections.h', 'WEB_JS_CONNECTIONS'),
    ('heater.js', 'web_js_heater.h', 'WEB_JS_HEATER'),
]:
    js = (root / 'hmi/web' / source).read_text(encoding='utf-8')
    assert ')JS"' not in js
    generated = ('#pragma once\n#include <Arduino.h>\n'
                 f'// Generated from hmi/web/{source}\n'
                 f'static const char {symbol}[] PROGMEM = R"JS(\n{js}\n)JS";\n')
    (web / header).write_text(generated, encoding='utf-8')
parts = [('web_html.h','WEB_HTML_TOP'),('web_js_core.h','WEB_JS_CORE'),
 ('web_js_dashboard.h','WEB_JS_DASH'),('web_js_profiles.h','WEB_JS_PROFILES'),
 ('web_js_calib.h','WEB_JS_CALIB'),('web_js_history.h','WEB_JS_HISTORY'),
 ('web_js_connections.h','WEB_JS_CONNECTIONS'),('web_js_heater.h','WEB_JS_HEATER'),
 ('web_js_system.h','WEB_JS_SYSTEM'),('legacy_hmi_extension.h','WEB_JS_HMI_SYSTEM'),
 ('web_html.h','WEB_HTML_BOTTOM')]
body = b''
for filename, name in parts:
    match = re.search(r'\b'+name+r'\[\].*?R"(\w+)\((.*?)\)\1"',
                      (web/filename).read_text(encoding='utf-8'), re.S)
    assert match, name
    body += match[2].encode('utf-8')
packed = gzip.compress(body, mtime=0)
etag = hashlib.sha256(packed).hexdigest()[:16]
output = '#pragma once\n#include <Arduino.h>\n// Generated by scripts/package_hmi_web.py\n'
output += 'static const char HMI_WEB_ETAG[] = "\\"'+etag+'\\"";\n'
output += 'static const uint8_t HMI_WEB_GZIP[] PROGMEM = {\n'
output += '\n'.join(','.join(str(b) for b in packed[i:i+24])+',' for i in range(0,len(packed),24))+'\n};\n'
target = web/'web_root_gzip.h'
if not target.exists() or target.read_text(encoding='utf-8') != output:
    target.write_text(output, encoding='utf-8')
print(f'HMI Web: {len(body)} -> {len(packed)} bytes gzip, ETag {etag}')
