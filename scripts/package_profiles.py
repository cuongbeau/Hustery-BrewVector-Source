"""Package only the BrewVector Profiles editor; no firmware build."""
from pathlib import Path
import json
root = Path(__file__).resolve().parents[1]
css = '\n'.join((root / 'hmi/web' / name).read_text(encoding='utf-8') for name in ['profiles.css', 'profile-blocks.css', 'profile-inline.css'])
js = 'const profileStyles = ' + json.dumps(css, ensure_ascii=False) + ';\n'
js += '\n'.join((root / 'hmi/web' / f).read_text(encoding='utf-8') for f in ['profile-validation.js', 'profile-editor-model.js', 'profiles-preview.js', 'profiles.js', 'profile-editor-view.js', 'profile-inline-editor.js'])
assert ')JS"' not in js
(root / 'hmi/src/web/web_js_profiles.h').write_text('#pragma once\n#include <Arduino.h>\n// Generated by scripts/package_profiles.py\nstatic const char WEB_JS_PROFILES[] PROGMEM = R"JS(\n'+js+'\n)JS";\n', encoding='utf-8')
print('Packaged BrewVector Profiles editor.')
